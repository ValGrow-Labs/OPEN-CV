METHODS = ("coin", "paper")
SLOTS = ("1", "2", "3", "self")
MAX_TRIES = 3
REFERENCE_TOLERANCE_MM = 2.0
PHOTO_NAME = re.compile(
    r"^(?P<code>[A-Za-z0-9_-]{6,40})_paper_(?P<slot>[123]|self)_t(?P<try>[1-3])\.(jpe?g|png)$", re.I
)


# --------------------------------------------------------------------------- #
# Randomisation (method order, permuted blocks)
# --------------------------------------------------------------------------- #


def randomise(n: int, seed: int, block: int = 4) -> list[dict]:
    """Permuted-block allocation of method order: each block holds equal numbers of coin-first and
    paper-first. Generated by someone who does not run sessions; operators open one row at a time."""
    if block % 2:
        raise ValueError("block size must be even")
    rng = np.random.default_rng(seed)
    rows = []
    while len(rows) < n:
        b = ["coin_first"] * (block // 2) + ["paper_first"] * (block // 2)
        rng.shuffle(b)
        rows += [{"slot_number": len(rows) + i + 1, "order": o} for i, o in enumerate(b)]
    return rows[:n]


