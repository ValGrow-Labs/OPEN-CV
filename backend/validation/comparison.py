def _write_csv(path: Path, rows: list[dict], fields: list[str], append: bool = False) -> None:
    exists = append and path.exists() and path.stat().st_size > 0
    with path.open("a" if exists else "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        if not exists:
            w.writeheader()
        w.writerows(rows)


ATTEMPT_FIELDS = ["participant_code", "method", "slot", "try", "status", "reasons", "hand_length_mm", "hand_breadth_mm"]


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("randomise")
    r.add_argument("--n", type=int, required=True)
    r.add_argument("--seed", type=int, required=True)
    r.add_argument("--block", type=int, default=4)
    r.add_argument("--out", type=Path, required=True)
    s = sub.add_parser("sample-size")
    s.add_argument("--delta", type=float, default=1.5, help="minimum important mean difference in absolute error (mm)")
    s.add_argument("--ref-sd", type=float, default=1.0, help="SD of the reference (caliper) measurement error")
    s.add_argument("--power", type=float, default=0.8)
    ic = sub.add_parser("import-coin")
    ic.add_argument("records", type=Path)
    ic.add_argument("--out", type=Path, required=True)
    pp = sub.add_parser("process-paper")
    pp.add_argument("folder", type=Path)
    pp.add_argument("--paper", required=True)
    pp.add_argument("--out", type=Path, required=True)
    pp.add_argument("--delete-processed", action="store_true")
    pp.add_argument("--append", action="store_true", help="add to an existing attempts file (in-session processing)")
    nu = sub.add_parser("nuisance", help="blinded sample-size re-estimation after the feasibility phase")
    nu.add_argument("--participants", type=Path, required=True)
    nu.add_argument("--reference", type=Path, required=True)
    nu.add_argument("--attempts", type=Path, nargs="+", required=True)
    nu.add_argument("--delta", type=float, required=True, help="the minimum important difference fixed in the protocol")
    nu.add_argument("--planned-n", type=int, required=True)
    nu.add_argument("--max-n", type=int, required=True)
    an = sub.add_parser("analyse")
    an.add_argument("--participants", type=Path, required=True)
    an.add_argument("--reference", type=Path, required=True)
    an.add_argument("--attempts", type=Path, nargs="+", required=True)
    an.add_argument("--usability", type=Path)
    an.add_argument("--phase", default="confirmatory", choices=["feasibility", "confirmatory"])
    an.add_argument("--delta-mid", type=float)
    an.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)

    if a.cmd == "randomise":
        _write_csv(a.out, randomise(a.n, a.seed, a.block), ["slot_number", "order"])
        print(f"wrote {a.out}")
    elif a.cmd == "sample-size":
        print(sample_size_table(a.delta, a.ref_sd, a.power))
    elif a.cmd == "import-coin":
        rows = import_coin_records(a.records)
        _write_csv(a.out, rows, ATTEMPT_FIELDS)
        print(f"wrote {len(rows)} coin attempts to {a.out}")
    elif a.cmd == "process-paper":
        rows, skipped = process_paper_photos(a.folder, a.paper, a.delete_processed)
        _write_csv(a.out, rows, ATTEMPT_FIELDS, append=a.append)
        # Status only: the scan operator is blinded, so no measurement is printed.
        for r in rows:
            print(f"{r['participant_code']} slot {r['slot']} try {r['try']}: {r['status']}"
                  + (f" ({r['reasons']})" if r["reasons"] else ""))  # fmt: skip
        print(f"wrote {len(rows)} paper attempts to {a.out}" + (" (photos deleted)" if a.delete_processed else ""))
        if skipped:
            print(f"not processed (name does not match the protocol or unreadable): {skipped}", file=sys.stderr)
    elif a.cmd == "nuisance":
        attempts = [row for p in a.attempts for row in _read(p)]
        nui = nuisance_parameters(analyse(_read(a.participants), _read(a.reference), attempts, None, "feasibility"))
        print(json.dumps(nui, indent=2))
        if nui["sd_D_mm"] is not None and not math.isnan(nui["sd_D_mm"]):
            print(f"re-assessed confirmatory n: {reassessed_n(nui['sd_D_mm'], a.delta, a.planned_n, a.max_n)}")
    else:
        attempts = [row for p in a.attempts for row in _read(p)]
        res = analyse(_read(a.participants), _read(a.reference), attempts, _read(a.usability), a.phase, a.delta_mid)
        a.out.write_text(report_markdown(res), encoding="utf-8")
        print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
