"""Coin-on-palm vs flat-hand-on-paper comparison study (docs/COMPARISON_STUDY_PROTOCOL.md).

Tooling only. Nothing here changes either measurement method, and nothing here chooses a
method: it produces the pre-specified statistics for the study team to interpret.

Subcommands (from backend/)::

    python -m validation.comparison randomise --n 48 --seed <sealed seed> --out allocation.csv
    python -m validation.comparison sample-size [--delta 1.5] [--sd-coin 5 --sd-paper 4 --ref-sd 1]
    python -m validation.comparison import-coin <records.jsonl> --out coin_attempts.csv
    python -m validation.comparison process-paper <photo folder> --paper a4 --out paper_attempts.csv [--delete-processed]
    python -m validation.comparison analyse --participants p.csv --reference r.csv --attempts a.csv [--usability u.csv]
        [--phase confirmatory] [--delta-mid 1.5] --out report.md

Data files (templates in validation/templates/comparison_*.csv):

* participants: participant_code, phase (feasibility|confirmatory), order (coin_first|paper_first)
* reference: participant_code, hand, measurer, length_tool, length_r1..r3 (mm), breadth_tool, breadth_r1..r3 (mm)
* attempts: participant_code, method (coin|paper), slot (1|2|3|self), try (1..3), status
  (accepted|rejected), reasons, hand_length_mm, hand_breadth_mm
* usability: participant_code, method, seconds_to_first_accepted, ease_1to7
"""

