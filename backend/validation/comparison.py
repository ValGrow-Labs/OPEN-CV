def _read(path: Path | None) -> list[dict]:
    if path is None:
        return []
    with path.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def _num(v) -> float | None:
    return None if v in (None, "") else float(v)


def reference_value(readings: list[float | None]) -> tuple[float | None, str]:
    """HL-1 repeat rule: two readings within 2 mm (mean), or the median of three when it agrees
    with another reading within 2 mm. Anything else is not a usable reference."""
    s = sorted(v for v in readings if v is not None)
    tol = REFERENCE_TOLERANCE_MM + 1e-9
    if len(s) < 2:
        return None, "not_repeated"
    if len(s) == 2:
        return ((s[0] + s[1]) / 2, "agreed") if s[1] - s[0] <= tol else (None, "discrepant")
    return (s[1], "agreed") if min(s[1] - s[0], s[2] - s[1]) <= tol else (None, "discrepant")


def _describe(err: np.ndarray) -> dict:
    n = int(err.size)
    if n == 0:
        return {"n": 0}
    sd = float(err.std(ddof=1)) if n > 1 else float("nan")
    bias = float(err.mean())
    return {"n": n, "bias_mm": bias, "mae_mm": float(np.abs(err).mean()), "rmse_mm": float(np.sqrt(np.mean(err**2))),
            "sd_mm": sd, "loa_mm": [bias - 1.96 * sd, bias + 1.96 * sd] if n > 1 else None}  # fmt: skip


def analyse(
    participants: list[dict],
    reference: list[dict],
    attempts: list[dict],
    usability: list[dict] | None = None,
    phase: str = "confirmatory",
    delta_mid: float | None = None,
    boot: int = 5000,
    seed: int = 0,
) -> dict:
    codes = {p["participant_code"] for p in participants if p["phase"] == phase}
    refs = {}
    ref_status = defaultdict(int)
    for r in reference:
        if r["participant_code"] not in codes:
            continue
        v, status = reference_value([_num(r.get(f"length_r{i}")) for i in (1, 2, 3)])
        b, _ = reference_value([_num(r.get(f"breadth_r{i}")) for i in (1, 2, 3)])
        refs[r["participant_code"]] = (v, b)
        ref_status[status] += 1

    by = defaultdict(list)  # (code, method) -> rows
    for a in attempts:
        if a["participant_code"] in codes:
            by[(a["participant_code"], a["method"])].append(a)

    def first_accepted(rows: list[dict], slot: str) -> dict | None:
        cand = [
            r for r in rows if r["slot"] == slot and r["status"] == "accepted" and _num(r["hand_length_mm"]) is not None
        ]
        return min(cand, key=lambda r: int(r["try"])) if cand else None

    per = {}
    for code in sorted(codes):
        ref_len = refs.get(code, (None, None))[0]
        for m in METHODS:
            rows = by.get((code, m), [])
            slot_vals = {s: first_accepted(rows, s) for s in SLOTS}
            per[(code, m)] = {
                "slot_values": {s: (_num(v["hand_length_mm"]) if v else None) for s, v in slot_vals.items()},
                "breadth_1": _num(slot_vals["1"]["hand_breadth_mm"]) if slot_vals["1"] and m == "paper" else None,
                "tries": len([r for r in rows if r["slot"] in SLOTS]),
                "rejected": sum(r["status"] == "rejected" for r in rows if r["slot"] in SLOTS),
                "ref": ref_len,
            }

    # Primary: absolute error of the slot-1 (first) accepted attempt, paired by participant.
    pairs = []
    for code in sorted(codes):
        c, p = per[(code, "coin")], per[(code, "paper")]
        if c["ref"] is None or c["slot_values"]["1"] is None or p["slot_values"]["1"] is None:
            continue
        pairs.append((code, c["slot_values"]["1"] - c["ref"], p["slot_values"]["1"] - p["ref"]))
    out: dict = {"phase": phase, "participants_in_phase": len(codes), "references": dict(ref_status)}
    if pairs:
        e_c = np.array([x[1] for x in pairs])
        e_p = np.array([x[2] for x in pairs])
        d = np.abs(e_c) - np.abs(e_p)
        n = len(d)
        mean, sd = float(d.mean()), float(d.std(ddof=1)) if n > 1 else float("nan")
        half = stats.t.ppf(0.975, n - 1) * sd / math.sqrt(n) if n > 1 else float("nan")
        rng = np.random.default_rng(seed)
        bs = rng.choice(d, (boot, n), replace=True).mean(axis=1) if n > 1 else np.array([mean])
        wil = stats.wilcoxon(d) if n > 1 and np.any(d != 0) else None
        primary = {
            "definition": "D = |coin error| - |paper error| of each participant's first accepted attempt (slot 1); "
            "positive D favours paper",
            "n_pairs": n,
            "mean_D_mm": mean,
            "sd_D_mm": sd,
            "ci95_t_mm": [mean - half, mean + half],
            "ci95_bootstrap_mm": [float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))],
            "wilcoxon_p": float(wil.pvalue) if wil is not None else None,
            "sd_signed_difference_mm": float((e_c - e_p).std(ddof=1)) if n > 1 else float("nan"),
        }
        if delta_mid is not None:
            lo, hi = primary["ci95_t_mm"]
            primary["prespecified_threshold_mm"] = delta_mid
            primary["criterion_paper_better"] = bool(lo > 0 and mean >= delta_mid)
            primary["criterion_coin_better"] = bool(hi < 0 and -mean >= delta_mid)
        out["primary"] = primary
        out["accuracy_slot1"] = {"coin": _describe(e_c), "paper": _describe(e_p)}
    out["excluded_from_primary"] = len(codes) - len(pairs)

    # Secondary: repeatability (slots 1-3), self-capture, rejections, breadth, usability.
    sec: dict = {}
    for m in METHODS:
        ss, dof, self_ok, self_n, tries, rej = 0.0, 0, 0, 0, 0, 0
        for code in codes:
            v = [x for s, x in per[(code, m)]["slot_values"].items() if s in ("1", "2", "3") and x is not None]
            if len(v) >= 2:
                arr = np.array(v)
                ss += float(((arr - arr.mean()) ** 2).sum())
                dof += len(arr) - 1
            self_n += 1
            self_ok += per[(code, m)]["slot_values"]["self"] is not None
            tries += per[(code, m)]["tries"]
            rej += per[(code, m)]["rejected"]
        w = math.sqrt(ss / dof) if dof else None
        self_err = [per[(c, m)]["slot_values"]["self"] - per[(c, m)]["ref"] for c in codes
                    if per[(c, m)]["slot_values"]["self"] is not None and per[(c, m)]["ref"] is not None]  # fmt: skip
        sec[m] = {
            "within_participant_sd_mm": w,
            "repeatability_coefficient_mm": 2.77 * w if w is not None else None,
            "tries": tries,
            "rejected_tries": rej,
            "rejection_rate": rej / tries if tries else None,
            "self_capture_success": f"{self_ok}/{self_n}",
            "self_capture_accuracy": _describe(np.array(self_err)),
        }
    breadth_err = [per[(c, "paper")]["breadth_1"] - refs[c][1] for c in codes
                   if per[(c, "paper")]["breadth_1"] is not None and refs.get(c, (None, None))[1] is not None]  # fmt: skip
    sec["paper_breadth_slot1"] = _describe(np.array(breadth_err))
    if usability:
        u = defaultdict(dict)
        for row in usability:
            if row["participant_code"] in codes:
                u[row["participant_code"]][row["method"]] = row
        paired = [(float(v["coin"]["ease_1to7"]), float(v["paper"]["ease_1to7"])) for v in u.values()
                  if "coin" in v and "paper" in v and v["coin"]["ease_1to7"] and v["paper"]["ease_1to7"]]  # fmt: skip
        secs = {m: [float(v[m]["seconds_to_first_accepted"]) for v in u.values()
                    if m in v and v[m]["seconds_to_first_accepted"]] for m in METHODS}  # fmt: skip
        sec["usability"] = {
            "ease_median": {
                m: float(np.median([p[i] for p in paired])) if paired else None for i, m in enumerate(METHODS)
            },
            "ease_pairs": len(paired),
            "seconds_median": {m: float(np.median(v)) if v else None for m, v in secs.items()},
        }
    out["secondary"] = sec
    return out


def nuisance_parameters(res: dict) -> dict:
    """Only what a sample-size re-estimation may use: spreads and operational rates. Every mean,
    bias, MAE and confidence interval is removed, so the people deciding on the sample size never
    see which method is ahead (docs/COMPARISON_STUDY_PROTOCOL.md, section 9)."""
    p = res.get("primary", {})
    acc = res.get("accuracy_slot1", {})
    return {
        "phase": res["phase"],
        "n_pairs": p.get("n_pairs", 0),
        "sd_D_mm": p.get("sd_D_mm"),
        "sd_signed_difference_mm": p.get("sd_signed_difference_mm"),
        "sd_error_mm": {m: acc.get(m, {}).get("sd_mm") for m in METHODS},
        "rejection_rate": {m: res["secondary"][m]["rejection_rate"] for m in METHODS},
        "within_participant_sd_mm": {m: res["secondary"][m]["within_participant_sd_mm"] for m in METHODS},
    }


def reassessed_n(sd_d: float, delta: float, planned_n: int, max_n: int, power: float = 0.8) -> int:
    """Sample size after the blinded re-estimation: the fixed minimum important difference with
    the observed SD of D. It may only grow (never shrink because of what was seen) and is capped."""
    return min(max_n, max(planned_n, required_n(delta, sd_d, power=power)))


def report_markdown(res: dict) -> str:
    def f(v, d=2):
        return "n/a" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v:.{d}f}"

    lines = [
        f"# Coin vs paper comparison: {res['phase']} analysis",
        "",
        "Pre-specified analysis (docs/COMPARISON_STUDY_PROTOCOL.md). Real participants only. These statistics",
        "do not choose a method by themselves; the study team applies the protocol's decision rule.",
        "",
        f"Participants in phase: {res['participants_in_phase']}; excluded from the primary analysis: "
        f"{res['excluded_from_primary']}; references: {res['references']}.",
        "",
    ]
    p = res.get("primary")
    if p:
        lines += [
            "## Primary outcome",
            "",
            p["definition"] + ".",
            "",
            f"* Pairs: {p['n_pairs']}; mean D = {f(p['mean_D_mm'])} mm (SD {f(p['sd_D_mm'])})",
            f"* 95% CI (paired t): {f(p['ci95_t_mm'][0])} to {f(p['ci95_t_mm'][1])} mm; bootstrap: "
            f"{f(p['ci95_bootstrap_mm'][0])} to {f(p['ci95_bootstrap_mm'][1])} mm; Wilcoxon p = {f(p['wilcoxon_p'], 3)}",
        ]
        if "prespecified_threshold_mm" in p:
            lines.append(
                f"* Pre-specified threshold {p['prespecified_threshold_mm']} mm: paper criterion "
                f"{'met' if p['criterion_paper_better'] else 'not met'}, coin criterion "
                f"{'met' if p['criterion_coin_better'] else 'not met'}"
            )
        lines += ["", "| Method (slot 1) | n | Bias | MAE | RMSE | SD | 95% LoA |", "|---|---|---|---|---|---|---|"]
        for m, d in res["accuracy_slot1"].items():
            loa = d.get("loa_mm")
            lines.append(f"| {m} | {d['n']} | {f(d.get('bias_mm'))} | {f(d.get('mae_mm'))} | {f(d.get('rmse_mm'))} | "
                         f"{f(d.get('sd_mm'))} | {f(loa[0]) + ' to ' + f(loa[1]) if loa else 'n/a'} |")  # fmt: skip
    else:
        lines += ["No complete pairs: no primary result.", ""]
    s = res["secondary"]
    lines += ["", "## Secondary outcomes (descriptive)", "", "| Method | Within-participant SD | Repeatability coefficient | "
              "Rejected tries | Self-capture success | Self-capture MAE |", "|---|---|---|---|---|---|"]  # fmt: skip
    for m in METHODS:
        d = s[m]
        lines.append(f"| {m} | {f(d['within_participant_sd_mm'])} | {f(d['repeatability_coefficient_mm'])} | "
                     f"{d['rejected_tries']}/{d['tries']} | {d['self_capture_success']} | "
                     f"{f(d['self_capture_accuracy'].get('mae_mm'))} |")  # fmt: skip
    b = s["paper_breadth_slot1"]
    lines += [
        "",
        f"Paper breadth vs calipers (slot 1): n = {b['n']}, bias {f(b.get('bias_mm'))} mm, MAE {f(b.get('mae_mm'))} mm.",
    ]
    if "usability" in s:
        u = s["usability"]
        lines.append(f"Usability: median ease {u['ease_median']} ({u['ease_pairs']} pairs); median seconds to first "
                     f"accepted attempt {u['seconds_median']}.")  # fmt: skip
    return "\n".join(lines) + "\n"


