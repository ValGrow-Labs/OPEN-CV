def assign_slots(tries: list[tuple[str, float | None, str]]) -> list[dict]:
    """Map a participant's chronological tries for one method onto the protocol's slots.

    The protocol fixes the sequence: slot 1, 2, 3 (operator-assisted) then 'self'. Each slot gets
    up to MAX_TRIES tries; a slot ends at its first accepted try or after MAX_TRIES rejections.
    Retakes are allowed only after a rejection by the app, never because of a value, so the
    sequence alone identifies every try."""
    rows, slot_i, n_try = [], 0, 0
    for status, value, reasons in tries:
        if slot_i >= len(SLOTS):
            rows.append({"slot": "extra", "try": None, "status": status, "hand_length_mm": value, "reasons": reasons})
            continue
        n_try += 1
        rows.append(
            {"slot": SLOTS[slot_i], "try": n_try, "status": status, "hand_length_mm": value, "reasons": reasons}
        )
        if status == "accepted" or n_try >= MAX_TRIES:
            slot_i, n_try = slot_i + 1, 0
    return rows


def import_coin_records(path: Path) -> list[dict]:
    """Coin attempts from validation-mode records (real participants, standard condition only)."""
    by_code: dict[str, list[dict]] = defaultdict(list)
    with path.open(encoding="utf-8") as f:
        for line in f:
            if line.strip():
                r = json.loads(line)
                if r.get("data_origin") == "real_participant" and r.get("trial", {}).get("condition") == "standard":
                    by_code[r["participant_code"]].append(r)
    rows = []
    for code, recs in sorted(by_code.items()):
        recs.sort(key=lambda r: r["created_at"])
        tries = []
        for r in recs:
            hl = next((c for c in r["comparisons"] if c["key"] == "hand_length_mm"), None)
            value = hl["estimate_mm"] if hl and hl["estimate_mm"] is not None else None
            status = "accepted" if r["quality_passed"] and value is not None else "rejected"
            tries.append((status, value, ";".join(r["scan_rejection_reasons"])))
        for row in assign_slots(tries):
            rows.append({"participant_code": code, "method": "coin", "hand_breadth_mm": None, **row})
    return rows


def process_paper_photos(folder: Path, paper: str, delete_processed: bool = False) -> tuple[list[dict], list[str]]:
    """Measure every protocol-named photo (<code>_paper_<slot>_t<try>.jpg) with the experimental
    paper method. Returns attempt rows and the names of files that did not match the naming
    scheme (left untouched). With ``delete_processed``, each photo is deleted right after its
    numbers have been extracted; files that fail to load are kept for the operator to check."""
    import cv2

    from experimental.paper_method.measure import measure_photo

    rows, skipped = [], []
    for f in sorted(folder.iterdir()):
        m = PHOTO_NAME.match(f.name)
        if not f.is_file() or not m:
            skipped.append(f.name)
            continue
        img = cv2.imread(str(f), cv2.IMREAD_COLOR)
        if img is None:
            skipped.append(f.name)
            continue
        r = measure_photo(img, paper)
        est = {e.key: e for e in r.estimates}
        rows.append({
            "participant_code": m["code"], "method": "paper", "slot": m["slot"].lower(), "try": int(m["try"]),
            "status": "accepted" if r.accepted else "rejected", "reasons": ";".join(r.reasons),
            "hand_length_mm": round(est["hand_length_mm"].value_mm, 2) if r.accepted else None,
            "hand_breadth_mm": round(est["hand_breadth_mm"].value_mm, 2) if r.accepted else None,
        })  # fmt: skip
        del img
        if delete_processed:
            f.unlink()
    return rows, skipped


