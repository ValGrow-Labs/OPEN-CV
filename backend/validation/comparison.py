def sd_paired_signed_difference(sd_coin: float, sd_paper: float, rho: float) -> float:
    """SD of (signed error coin - signed error paper) for one participant. Errors of the two
    methods are correlated (rho) because both are compared with the *same* reference
    measurement, whose own error cancels in the difference."""
    return math.sqrt(sd_coin**2 + sd_paper**2 - 2 * rho * sd_coin * sd_paper)


def required_n(delta: float, sd_diff: float, alpha: float = 0.05, power: float = 0.8) -> int:
    """Participants for a two-sided paired t-test to detect a mean paired difference ``delta``
    when the paired differences have SD ``sd_diff`` (iterated with the t distribution)."""
    z = stats.norm.ppf(1 - alpha / 2) + stats.norm.ppf(power)
    n = max(3, math.ceil((z * sd_diff / delta) ** 2))
    for _ in range(50):
        t = stats.t.ppf(1 - alpha / 2, n - 1) + stats.t.ppf(power, n - 1)
        n_new = max(3, math.ceil((t * sd_diff / delta) ** 2))
        if n_new == n:
            break
        n = n_new
    return n


@dataclass
class ErrorModel:
    """Planning assumptions for one method's single-attempt hand-length error (mm)."""

    bias: float
    sd: float  # method's own error, excluding reference measurement error


def simulate_abs_error_difference(
    n: int, coin: ErrorModel, paper: ErrorModel, ref_sd: float, alpha: float = 0.05, reps: int = 4000, seed: int = 0
) -> dict:
    """Monte Carlo for the primary outcome: D = |error coin| - |error paper| per participant.

    Errors are taken against the reference measurement, so both share the reference's own error
    (SD ``ref_sd``); that shared term makes the methods' errors correlated. Absolute errors are
    not normal, so the SD of D and the power are simulated rather than taken from a formula."""
    rng = np.random.default_rng(seed)
    r = rng.normal(0, ref_sd, (reps, n))
    e_c = coin.bias + rng.normal(0, coin.sd, (reps, n)) - r
    e_p = paper.bias + rng.normal(0, paper.sd, (reps, n)) - r
    d = np.abs(e_c) - np.abs(e_p)
    mean, sd = d.mean(axis=1), d.std(axis=1, ddof=1)
    t = mean / (sd / math.sqrt(n))
    crit = stats.t.ppf(1 - alpha / 2, n - 1)
    return {
        "n": n,
        "true_mean_difference_mm": float(d.mean()),
        "sd_of_difference_mm": float(np.sqrt(d.var(axis=1, ddof=1).mean())),
        "power_two_sided": float(np.mean(np.abs(t) > crit)),
    }


def sample_size_table(delta: float, ref_sd: float = 1.0, power: float = 0.8, sds=(3.0, 4.0, 5.0, 6.0)) -> str:
    """Planning grid. For each pair of per-method error SDs (unbiased methods, the hardest case for
    the SD of D), the simulated SD of the paired difference D = |e_coin| - |e_paper| and the
    participants needed to detect a true mean D of ``delta``. The 'naive' column shows the
    (wrong) size obtained by plugging an individual method's error SD in as if it were SD(D)."""
    lines = [
        f"Target: detect a true mean difference in absolute error of {delta} mm, two-sided alpha 0.05, power {power:.0%};",
        f"reference (caliper) error SD {ref_sd} mm shared by both methods. Planning assumptions, not results.",
        "",
        "| SD coin error | SD paper error | SD of D (simulated) | n (paired, this table) | naive n using SD coin error |",
        "|---|---|---|---|---|",
    ]
    for sd_c in sds:
        for sd_p in sds:
            if sd_p > sd_c:
                continue
            sim = simulate_abs_error_difference(400, ErrorModel(0.0, sd_c), ErrorModel(0.0, sd_p), ref_sd, reps=400)
            sd_d = sim["sd_of_difference_mm"]
            lines.append(f"| {sd_c:g} | {sd_p:g} | {sd_d:.2f} | {required_n(delta, sd_d, power=power)} | "
                         f"{required_n(delta, sd_c, power=power)} |")  # fmt: skip
    return "\n".join(lines)


