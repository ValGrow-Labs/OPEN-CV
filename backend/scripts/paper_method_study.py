"""Paper-method study: how capture geometry affects the EXPERIMENTAL flat-hand-on-paper method.

Runs experimental/paper_method on pinhole-camera renderings with a known hand (185 mm length,
84 mm breadth) and writes docs/PAPER_METHOD_STUDY.md.

These are SYNTHETIC results about geometry. They do not measure real-world accuracy and must
not be compared with real-hand results as if they were.

Usage (from backend/):  python -m scripts.paper_method_study
"""

from __future__ import annotations

from dataclasses import replace

from experimental.paper_method.config import load_config
from experimental.paper_method.measure import measure_photo
from experimental.paper_method.synthetic import PaperScene, mcp_landmarks_px, render
from glovesize.config import REPO_ROOT

TYPICAL = PaperScene(finger_height_mm=5.0, palm_height_mm=12.0)

SCENARIOS: list[tuple[str, PaperScene, str]] = [
    ("Outline in the sheet plane (zero thickness), camera 380 mm overhead", PaperScene(), "a4"),
    ("Typical thickness (outline 5 mm at fingertip, 12 mm at palm edge)", TYPICAL, "a4"),
    ("Thin hand (3 / 7 mm)", replace(TYPICAL, finger_height_mm=3.0, palm_height_mm=7.0), "a4"),
    ("Thick hand (8 / 18 mm)", replace(TYPICAL, finger_height_mm=8.0, palm_height_mm=18.0), "a4"),
    ("Camera tilted 15 deg", replace(TYPICAL, tilt_deg=15, tilt_azimuth_deg=40), "a4"),
    ("Camera tilted 30 deg", replace(TYPICAL, tilt_deg=30, tilt_azimuth_deg=220), "a4"),
    ("Tilted 20 deg about an axis parallel to a sheet edge", replace(TYPICAL, tilt_deg=20, tilt_azimuth_deg=90), "a4"),
    ("Camera 280 mm away", replace(TYPICAL, camera_distance_mm=280), "a4"),
    ("Camera 500 mm away", replace(TYPICAL, camera_distance_mm=500), "a4"),
    ("Camera above the fingertips, not the sheet centre", replace(TYPICAL, target_mm=(105.0, 80.0)), "a4"),
    ("Hand rotated 8 deg on the sheet", replace(TYPICAL, hand_rotation_deg=8), "a4"),
    ("Wrist crease 3 mm inside the sheet edge", replace(TYPICAL, crease_offset_mm=3), "a4"),
    ("Wrist crease 3 mm beyond the sheet edge", replace(TYPICAL, crease_offset_mm=-3), "a4"),
    ("Dark skin", replace(TYPICAL, skin_bgr=(55, 70, 95)), "a4"),
    ("US Letter sheet", replace(TYPICAL, sheet="letter"), "letter"),
    ("Mild barrel distortion (k1 = -0.02)", replace(TYPICAL, k1=-0.02), "a4"),
    ("Strong barrel distortion (k1 = -0.06)", replace(TYPICAL, k1=-0.06), "a4"),
    ("US Letter sheet, A4 selected", replace(TYPICAL, sheet="letter"), "a4"),
    ("Thumb held against the palm", replace(TYPICAL, thumb_adducted=True), "a4"),
]


def _pct(v: float, truth: float) -> str:
    return f"{v - truth:+.2f} mm ({100 * (v - truth) / truth:+.2f}%)"


def run(scene: PaperScene, paper: str) -> list[str]:
    img, cam = render(scene)
    r = measure_photo(img, paper, mcp_landmarks_px(scene, cam))
    if not r.estimates:
        return ["rejected: " + ", ".join(r.reasons)] + [""] * 4
    est = {e.key: e for e in r.estimates}
    L, B = est["hand_length_mm"], est["hand_breadth_mm"]  # noqa: N806
    status = "accepted" if r.accepted else "flagged: " + ", ".join(r.reasons)
    return [
        status,
        _pct(L.raw_mm, scene.hand_length_mm),
        _pct(L.value_mm, scene.hand_length_mm),
        _pct(B.raw_mm, scene.breadth_mm),
        _pct(B.value_mm, scene.breadth_mm),
    ]


def main() -> None:
    ga = load_config().geometry_assumptions
    lines = [
        "# Paper-method study (synthetic geometry)",
        "",
        "Generated by `backend/scripts/paper_method_study.py` with the pinhole renderer in",
        "`backend/experimental/paper_method/synthetic.py`. **These are synthetic software results about",
        "geometry, not real-world accuracy.** The rendered hand is a simplified flat shape (true hand length",
        "185 mm, breadth 84 mm) whose outline is drawn at a fixed height above the sheet. Real hands, real",
        "cameras, real paper and real customers are not simulated; see `docs/PAPER_METHOD_EVALUATION.md`.",
        "",
        "Columns: error of the raw outline measurement, and after the assumption-based adjustment for the",
        f"outline's height above the sheet (assumed {ga.silhouette_height_mm.fingertip:g} mm at the fingertip and "
        f"{ga.silhouette_height_mm.palm_edge:g} mm at the palm edge,",
        "with the camera position recovered from the sheet). The metacarpal level comes from simulated MCP",
        "landmarks. Image 1600 x 1200, field of view 65 deg.",
        "",
        "| Scenario | Result | Length, raw | Length, adjusted | Breadth, raw | Breadth, adjusted |",
        "|---|---|---|---|---|---|",
    ]
    for name, scene, paper in SCENARIOS:
        lines.append(f"| {name} | " + " | ".join(run(scene, paper)) + " |")
    lines += [
        "",
        "Reading the table:",
        "",
        "* The sheet's homography maps points *on the sheet* exactly at any tilt, so the scale and perspective",
        "  of the sheet itself are not error sources here (sub-pixel corners, see the tests).",
        "* The hand's outline is *above* the sheet. Seen from a finite distance it is displaced away from the",
        "  point below the camera, so breadth reads wide (several percent) and length slightly long. The",
        "  adjustment removes this only when the assumed outline heights match the hand (the thin and thick",
        "  rows show the error when they do not).",
        "* The wrist end is defined by placing the wrist crease on the sheet edge. Any misplacement goes",
        "  straight into hand length and is invisible in the image.",
    ]
    path = REPO_ROOT / "docs" / "PAPER_METHOD_STUDY.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
